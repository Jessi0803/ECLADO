    assert.equal((await query('select stock from public.products where id = 10'))[0].stock, 10);
    assert.equal((await query("select count(*)::int as n from public.audit_logs where action = 'inventory_receipts.post'"))[0].n, 1);
    const product = { id: 10, name: 'Test', name_zh: '測試品', category: 'face', publication_status: 'active' };
    const variants = [
      { id: '101', sku: 'NEW-A', size: '100ml', price: 300, pro_price: 200, stock: 8, is_default: true },
      { id: '102', sku: 'B', size: '200ml', price: 300, pro_price: 200, stock: 3 },
    ];
    const saveCatalog = lines => result('select public.save_product_with_variants($1, $2) result',
      [JSON.stringify(product), JSON.stringify(lines)]);
    await saveCatalog(variants); // Old bundles send stock without an original value.
    assert.deepEqual(await stocks(), [10, 4]);
    const stale = variants.map(line => ({ ...line, expected_stock: line.stock }));
    await saveCatalog(stale);
    assert.deepEqual(await stocks(), [10, 4]);
    await assert.rejects(saveCatalog([{ ...stale[0], stock: 20 }, stale[1]]), { code: '40001' });
    await saveCatalog([{ ...stale[0], stock: 11, expected_stock: 10, unit_weight_g: 310 }, stale[1]]);
    assert.deepEqual(await stocks(), [11, 4]);
    const [option] = await result("select public.search_inventory_receipt_variants('NEW-A') result");
    assert.equal(option.unit_weight_g, 310);

    // Failure on any line rolls back the entire post and leaves the preview available.
