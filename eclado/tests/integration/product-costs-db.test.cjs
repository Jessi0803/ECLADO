const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { pathToFileURL } = require('node:url');
const { test } = require('node:test');

const read = name => readFileSync(resolve(__dirname, '../..', name), 'utf8');

test('FIFO uses whole fulfillment lines, preserves shortages, and handles opening, adjustments and returns', {
  skip: !process.env.PGLITE_MODULE,
}, async () => {
  const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
  const db = new PGlite();
  const query = async (sql, args = []) => (await db.query(sql, args)).rows;
  const result = async (sql, args) => (await query(sql, args))[0].result;
  const actor = '11111111-1111-4111-8111-111111111111';
  const cutoff = '2020-01-15T00:00:00Z';
  const run = until => result('select public.run_product_costs(250,$1) result', [until]);
  const summary = () => result("select public.get_product_cost_summary('2020-01-15','2020-01-15') result");

  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql as
        $$ select nullif(current_setting('test.uid', true),'')::uuid $$;
      create function public.has_backoffice_permission(permission text) returns boolean language sql as
        $$ select permission = any(string_to_array(coalesce(current_setting('test.permissions',true),''),',')) $$;
      create table public.products (
        id integer generated by default as identity primary key, asset_key uuid, name text, name_zh text,
        subtitle text, category text, series text, min_stock integer default 3, is_pro_only boolean,
        apply_tier_multiplier boolean, image_url text, image_urls jsonb, description text, skin_type text,
        ingredients text, features jsonb, source_folder_name text, imported_from_drive boolean,
        product_list_image_scale numeric, publication_status text, active boolean, size text, price numeric,
        pro_price numeric, stock integer, variants jsonb, updated_at timestamptz
      );
      create table public.product_variants (
        id bigint generated by default as identity primary key, product_id integer references public.products(id),
        sku text, size text, price numeric, pro_price numeric, stock integer not null, is_default boolean,
        is_custom_order boolean, procurement_unit_cost_usd numeric, gift_enabled boolean, gift_stock integer,
        gift_min_stock integer, sort_order integer, active boolean, updated_at timestamptz
      );
      create table public.orders (id text primary key, status text, fulfillment_method text, order_source text,
        shipped_at timestamptz, items jsonb);
      create table public.order_inventory_allocations (
        order_id text, item_index integer, product_variant_id bigint, stock_deducted_qty integer, state text,
        line_type text, backorder_qty integer, unique(order_id,item_index)
      );
      create table public.inventory_receipts (id uuid primary key, receipt_no bigint, posted_at timestamptz, received_on date);
      create table public.inventory_receipt_items (receipt_id uuid, variant_id bigint, quantity integer, unit_cost_twd numeric);
      create table public.audit_logs (entity_type text, entity_id text, created_at timestamptz, before_data jsonb, after_data jsonb);
      create table public.inventory_count_sessions (id uuid primary key, status text, completed_at timestamptz);
      create table public.inventory_count_items (id bigint primary key, session_id uuid, product_variant_id bigint,
        inventory_type text, applied_delta integer);
      create table public.inventory_count_shortages (count_item_id bigint, allocation_id bigint, quantity integer);
      insert into public.products (id,name,name_zh,category,publication_status,active,stock)
        values (10,'Test','測試品','face','active',true,2);
      insert into public.product_variants (id,product_id,sku,size,price,pro_price,stock,is_default,active,gift_stock)
        values (101,10,'A','100ml',300,200,2,true,true,0), (102,10,'B','200ml',300,200,1,false,true,0),
               (103,10,'EXCLUDED','300ml',300,200,10,false,false,0);
      insert into public.orders values
        ('A-HELD','unpaid','delivery','admin_assisted',null,'[]'),
        ('A-OLD','shipped','delivery','online','2019-01-01T00:00:00Z','[{"variant_id":101,"qty":10}]'),
        ('A-HISTORY','paid','delivery','historical_manual',null,'[]');
      insert into public.order_inventory_allocations values
        ('A-HELD',0,101,1,'allocated','merchandise',0),
        ('A-OLD',0,101,10,'allocated','merchandise',0),
        ('A-HISTORY',0,101,9,'allocated','merchandise',0);
      select set_config('test.uid','${actor}',false);
      select set_config('test.permissions','catalog.write,procurement.manage,analytics.read',false);
    `);
    await db.exec(read('supabase-save-product-with-variants.sql'));
    const migration = read('supabase-product-costs.sql');
    await db.exec(migration);
    await db.exec(migration);
    const opening = [
      { variant_id: 101, quantity: 2, unit_cost_twd: 100, evidence: '期初單 A' },
      { variant_id: 101, quantity: 1, unit_cost_twd: 110, evidence: '期初單 B' },
    ];
    assert.equal((await summary()).started_at, null);
    await assert.rejects(result('select public.start_product_costs($1) result',
      [JSON.stringify([{ ...opening[0], quantity: 4 }])]), { code: '22023' });
    const startWithExclusions = (lines, exclusions) => result(
      'select public.start_product_costs($1,$2::bigint[]) result', [JSON.stringify(lines), exclusions],
    );
    await assert.rejects(startWithExclusions(opening, [999]), { code: '22023' });
    await assert.rejects(startWithExclusions(opening, [101]), { code: '22023' });
    await startWithExclusions(opening, [103]);
    assert.equal((await query("select sum(quantity)::int as n from product_cost_events where kind='opening'"))[0].n, 4);
    assert.deepEqual(await query(
      "select variant_id::int, quantity from product_cost_events where kind='opening' and unit_cost_twd is null",
    ), [{ variant_id: 102, quantity: 1 }]);

    // Rebase the isolated fixture so simulated events can use stable historical timestamps.
    await query('update product_cost_cutover set started_at=$1', [cutoff]);
    await query("update product_cost_events set occurred_at=$1 where kind='opening'", [cutoff]);
    await db.exec(`
      insert into public.inventory_receipts values
        ('22222222-2222-4222-8222-222222222221',1,'2020-01-15 01:00Z','2020-01-15'),
        ('22222222-2222-4222-8222-222222222222',2,'2020-01-15 04:00Z','2020-01-15');
      insert into public.inventory_receipt_items values
        ('22222222-2222-4222-8222-222222222221',101,2,130),
        ('22222222-2222-4222-8222-222222222222',101,2,150);
      insert into public.orders values
        ('S1','shipped','delivery','online','2020-01-15 02:00Z','[{"variant_id":"101","qty":4},{"variant_id":"101","qty":7,"line_type":"gift"}]'),
        ('S2','shipped','delivery','online','2020-01-15 03:00Z','[{"variant_id":"101","qty":3}]'),
        ('P1','picked_up','onsite_pickup','admin_assisted',null,'[{"qty":1}]'),
        ('PENDING','ready_for_pickup','onsite_pickup','online',null,'[{"variant_id":"101","qty":2}]');
      insert into public.audit_logs values
        ('orders','P1','2020-01-15 03:30Z','{"status":"ready_for_pickup"}','{"status":"picked_up"}'),
        ('orders','S1','2020-01-15 02:15Z','{"status":"shipped"}','{"status":"shipped"}');
      insert into public.order_inventory_allocations values
        ('S2',0,101,1,'partial','merchandise',2), ('P1',0,102,1,'allocated','merchandise',0);
      insert into public.inventory_count_sessions values ('33333333-3333-4333-8333-333333333333','completed','2020-01-15 04:30Z');
      insert into public.inventory_count_items values (1,'33333333-3333-4333-8333-333333333333',101,'sale',1);
    `);
    await db.exec('set role authenticated');
    await assert.rejects(run('2020-01-15T05:00:00Z'), { code: '42501' });
    await assert.rejects(query('select * from public.product_cost_entries'), { code: '42501' });
    await db.exec('reset role; set role service_role');
    assert.ok(await run('2020-01-15T05:00:00Z') > 0);
    assert.equal(await run('2020-01-15T05:00:00Z'), 0);
    await db.exec('reset role');

    const entries = await query(`
      select event.order_id, event.line_index, entry.quantity, entry.unit_cost_twd, entry.reason
      from public.product_cost_entries entry join public.product_cost_events event on event.event_key=entry.event_key
      where event.kind='shipment' order by event.order_id, entry.id
    `);
    assert.deepEqual(entries.map(row => [row.order_id,row.line_index,row.quantity,row.unit_cost_twd,row.reason]), [
      ['P1',0,1,null,'unknown_cost'], ['S1',0,2,'100',null], ['S1',0,1,'110',null], ['S1',0,1,'130',null],
      ['S2',0,1,'130',null], ['S2',0,2,null,'layer_shortage'],
    ]);
    const report = await summary();
    assert.equal(report.shipment_cost, 570);
    assert.equal(report.pending_quantity, 3);
    assert.equal(report.shortage_quantity, 2);
    assert.equal(report.unknown_quantity, 1);
    assert.equal(report.pending_items.length, 2);
    assert.equal(report.processed_through, '2020-01-15T05:00:00+00:00');
    const shortage = report.pending_items.find(item => item.order_id === 'S2');
    assert.equal(shortage.reference_receipt_no, '1');
    assert.equal(shortage.suggested_unit_cost_twd, 130); // Ignore the later receipt at 150.
    const unknown = report.pending_items.find(item => item.order_id === 'P1');
    assert.equal(unknown.suggested_unit_cost_twd, null);
    const originalEntries = await query('select * from product_cost_entries order by id');
    const originalLayers = await query('select * from product_cost_layers order by id');
    const originalStock = await query('select id, stock from product_variants order by id');
    const approve = (cost, evidence) => result('select public.approve_product_cost_estimate($1,$2,$3) result',
      [shortage.entry_id, cost, evidence]);
    await assert.rejects(approve(130, '字'.repeat(501)), { code: '22023' });
    await db.exec("select set_config('test.permissions','analytics.read',false); set role authenticated");
    await assert.rejects(approve(130, '唯讀不可核准'), { code: '42501' });
    await db.exec("reset role; select set_config('test.permissions','catalog.write,procurement.manage,analytics.read',false); set role authenticated");
    await approve(132.125, '  ');
    await assert.rejects(approve(130, '重複核准'), { code: '40001' });
    const approved = await summary();
    assert.equal(approved.shipment_cost, 834.25);
    assert.equal(approved.estimated_cost, 264.25);
    assert.equal(approved.pending_quantity, 1);
    assert.equal(approved.approved_items[0].reference_receipt_no, '1');
    assert.equal(approved.approved_items[0].evidence, '');
    await db.exec('reset role');
    assert.deepEqual(await query('select * from product_cost_entries order by id'), originalEntries);
    assert.deepEqual(await query('select * from product_cost_layers order by id'), originalLayers);
    assert.deepEqual(await query('select id, stock from product_variants order by id'), originalStock);

    // Actual catalog saves create an adjustment; an unrelated stock change does not.
    await db.exec('update product_variants set stock = 1 where id = 102');
    await result('select public.save_product_with_variants($1,$2) result', [
      JSON.stringify({ id:10, name:'Test', name_zh:'測試品', category:'face', publication_status:'active' }),
      JSON.stringify([
        { id:'101', sku:'A', size:'100ml', price:300, pro_price:200, stock:0, is_default:true },
        { id:'102', sku:'B', size:'200ml', price:300, pro_price:200, stock:1 },
      ]),
    ]);
    const manual = await query("select event_key, quantity from product_cost_events where kind='manual'");
    assert.equal(manual.length, 1);
    assert.equal(manual[0].quantity, -2);
    await query("update product_cost_events set occurred_at='2020-01-15 05:10Z' where event_key=$1", [manual[0].event_key]);
    const refund = "select public.record_product_cost_return('44444444-4444-4444-8444-444444444444','S1',0,1,'實物回倉可再售') result";
    await result(refund);
    await result(refund);
    await db.exec("update product_cost_events set occurred_at='2020-01-15 05:20Z' where kind='return'");
    assert.equal(await run('2020-01-15T06:00:00Z'), 2);
    const adjustments = await query(`
      select entry.quantity, entry.unit_cost_twd, entry.estimated
      from public.product_cost_entries entry where event_key=$1 order by id
    `, [manual[0].event_key]);
    assert.deepEqual(adjustments, [
      { quantity:1, unit_cost_twd:'150', estimated:true },
      { quantity:1, unit_cost_twd:'150', estimated:false },
    ]);
    assert.equal((await summary()).return_cost, 130);
    assert.equal((await query("select count(*)::int as n from product_cost_events where kind='return'"))[0].n, 1);
    await assert.rejects(result("select public.record_product_cost_return(gen_random_uuid(),'S1',0,4,'超量') result"), { code: '22023' });

    await db.exec("select set_config('test.permissions','catalog.write',false); set role authenticated");
    await assert.rejects(summary(), { code: '42501' });
    await assert.rejects(result(refund), { code: '42501' });
  } finally {
    await db.close();
  }
});
