-- Price changes are append-only. This function closes the previous open-ended
-- version and inserts the next version atomically. The previous row is returned
-- unchanged when the submitted currency and cost already match.
create or replace function public.set_supplier_item_price(
  p_supplier_item_id bigint,
  p_unit_cost numeric,
  p_currency text default 'USD',
  p_effective_from timestamptz default now(),
  p_note text default null
)
returns public.supplier_item_prices
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_currency text := upper(btrim(coalesce(p_currency, '')));
  previous_price public.supplier_item_prices%rowtype;
  inserted_price public.supplier_item_prices%rowtype;
begin
  if not public.is_eclado_admin() and coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Administrator access required';
  end if;

  if p_unit_cost is null or p_unit_cost < 0 then
    raise exception 'Unit cost must be zero or greater';
  end if;

  if normalized_currency !~ '^[A-Z]{3}$' then
    raise exception 'Currency must be a three-letter ISO code';
  end if;

  if p_effective_from is null then
    raise exception 'Effective time is required';
  end if;

  -- Lock the parent row so concurrent price changes for one item serialize.
  perform 1
  from public.supplier_items
  where id = p_supplier_item_id
  for update;

  if not found then
    raise exception 'Supplier item % does not exist', p_supplier_item_id;
  end if;

  select *
  into previous_price
  from public.supplier_item_prices
  where supplier_item_id = p_supplier_item_id
    and effective_to is null
  order by effective_from desc, id desc
  limit 1
  for update;

  if found then
    if previous_price.currency = normalized_currency
       and previous_price.unit_cost = p_unit_cost then
      return previous_price;
    end if;

    if p_effective_from <= previous_price.effective_from then
      raise exception 'New effective time must be later than the current price start time';
    end if;

    update public.supplier_item_prices
    set effective_to = p_effective_from
    where id = previous_price.id;
  end if;

  insert into public.supplier_item_prices (
    supplier_item_id,
    currency,
    unit_cost,
    effective_from,
    note,
    created_by
  ) values (
    p_supplier_item_id,
    normalized_currency,
    p_unit_cost,
    p_effective_from,
    nullif(btrim(coalesce(p_note, '')), ''),
    auth.uid()
  )
  returning * into inserted_price;

  return inserted_price;
end;
$$;

revoke all on function public.set_supplier_item_price(bigint, numeric, text, timestamptz, text)
