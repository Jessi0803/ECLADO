create extension if not exists btree_gist with schema extensions;

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  default_currency text not null default 'USD',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint suppliers_code_not_blank check (btrim(code) <> ''),
  constraint suppliers_name_not_blank check (btrim(name) <> ''),
  constraint suppliers_default_currency_iso check (
    default_currency = upper(default_currency)
    and default_currency ~ '^[A-Z]{3}$'
  )
);

create unique index if not exists suppliers_code_unique
  on public.suppliers (lower(code));

create table if not exists public.supplier_items (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id) on delete restrict,
  supplier_sku text not null,
  name_en text not null,
  name_zh text,
  specification text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint supplier_items_sku_not_blank check (btrim(supplier_sku) <> ''),
  constraint supplier_items_name_en_not_blank check (btrim(name_en) <> '')
);

create unique index if not exists supplier_items_supplier_sku_unique
  on public.supplier_items (supplier_id, lower(supplier_sku));

create index if not exists supplier_items_supplier_active_idx
  on public.supplier_items (supplier_id, active, supplier_sku);

create table if not exists public.supplier_item_variant_links (
  supplier_item_id bigint not null references public.supplier_items(id) on delete cascade,
  product_variant_id bigint not null references public.product_variants(id) on delete cascade,
  conversion_quantity numeric(14, 4) not null default 1,
  is_primary boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (supplier_item_id, product_variant_id),
  constraint supplier_item_links_conversion_positive check (conversion_quantity > 0)
);

-- A storefront variant may have alternative supplier items, but only one primary
-- supplier item. An unlinked supplier item remains fully usable for procurement.
create unique index if not exists supplier_item_variant_primary_unique
  on public.supplier_item_variant_links (product_variant_id)
  where is_primary is true;

create index if not exists supplier_item_variant_links_variant_idx
  on public.supplier_item_variant_links (product_variant_id, supplier_item_id);

create table if not exists public.supplier_item_prices (
  id bigint generated by default as identity primary key,
  supplier_item_id bigint not null references public.supplier_items(id) on delete restrict,
  currency text not null default 'USD',
  unit_cost numeric(14, 4) not null,
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint supplier_item_prices_currency_iso check (
    currency = upper(currency)
    and currency ~ '^[A-Z]{3}$'
  ),
  constraint supplier_item_prices_cost_nonnegative check (unit_cost >= 0),
  constraint supplier_item_prices_valid_range check (
    effective_to is null or effective_to > effective_from
  )
);

-- Each supplier item has at most one open-ended price version.
create unique index if not exists supplier_item_prices_open_ended_unique
  on public.supplier_item_prices (supplier_item_id)
  where effective_to is null;

create index if not exists supplier_item_prices_history_idx
  on public.supplier_item_prices (supplier_item_id, effective_from desc);

-- Also prevent overlaps among closed historical ranges.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.supplier_item_prices'::regclass
      and conname = 'supplier_item_prices_no_overlap'
  ) then
    alter table public.supplier_item_prices
      add constraint supplier_item_prices_no_overlap
      exclude using gist (
        supplier_item_id with =,
        tstzrange(
          effective_from,
          coalesce(effective_to, 'infinity'::timestamptz),
          '[)'
        ) with &&
      );
  end if;
end;
$$;

