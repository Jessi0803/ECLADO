-- ECLADO procurement purchase orders, line-item snapshots and reusable addresses.
-- Run after supabase-procurement-catalog.sql and supabase-admin-users.sql.

create sequence if not exists public.purchase_order_number_seq;

create or replace function public.next_purchase_order_number()
returns text
language sql
volatile
security definer
set search_path = ''
as $$
  select 'PO-' || to_char(now() at time zone 'Asia/Taipei', 'YYYYMMDD') || '-'
    || lpad(nextval('public.purchase_order_number_seq')::text, 4, '0');
$$;

revoke all on function public.next_purchase_order_number() from public, anon, authenticated;

create table if not exists public.procurement_addresses (
  id bigint generated by default as identity primary key,
  address_text text not null,
  is_default boolean not null default false,
  active boolean not null default true,
  usage_count integer not null default 0 check (usage_count >= 0),
  last_used_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint procurement_addresses_address_not_blank check (btrim(address_text) <> '')
);

-- Remove the earlier split-address design when this migration is rerun.
alter table public.procurement_addresses
  drop column if exists label,
  drop column if exists recipient_name,
  drop column if exists country,
  drop column if exists postal_code,
  drop column if exists phone;

create unique index if not exists procurement_addresses_one_default
  on public.procurement_addresses (is_default)
  where is_default is true and active is true;

create table if not exists public.purchase_orders (
  id bigint generated by default as identity primary key,
  po_number text not null default public.next_purchase_order_number(),
  supplier_id bigint not null references public.suppliers(id) on delete restrict,
  status text not null default 'draft',
  currency text not null default 'USD',
  exchange_rate numeric(14, 6) not null,
  total_usd numeric(14, 2) not null default 0,
  total_twd numeric(14, 2) not null default 0,
  shipping_address jsonb not null default '{}'::jsonb,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ordered_at timestamptz,
  received_at timestamptz,
  constraint purchase_orders_po_number_unique unique (po_number),
  constraint purchase_orders_status_valid check (
    status in ('draft', 'pending', 'ordered', 'shipping', 'received', 'cancelled')
  ),
  constraint purchase_orders_currency_usd check (currency = 'USD'),
  constraint purchase_orders_exchange_rate_positive check (exchange_rate > 0),
  constraint purchase_orders_totals_nonnegative check (total_usd >= 0 and total_twd >= 0)
);

create index if not exists purchase_orders_created_idx
  on public.purchase_orders (created_at desc, id desc);

create table if not exists public.purchase_order_items (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id) on delete cascade,
  supplier_item_id bigint not null references public.supplier_items(id) on delete restrict,
  supplier_price_id bigint references public.supplier_item_prices(id) on delete set null,
  supplier_sku text not null,
  name_zh text,
  name_en text not null,
  specification text,
  quantity integer not null,
  currency text not null default 'USD',
  unit_cost numeric(14, 4) not null,
  subtotal_usd numeric(14, 2) not null,
  stock_at_order integer,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint purchase_order_items_quantity_positive check (quantity > 0),
  constraint purchase_order_items_currency_usd check (currency = 'USD'),
  constraint purchase_order_items_cost_nonnegative check (unit_cost >= 0 and subtotal_usd >= 0),
  constraint purchase_order_items_unique_item unique (purchase_order_id, supplier_item_id)
);

create index if not exists purchase_order_items_order_idx
  on public.purchase_order_items (purchase_order_id, sort_order, id);

drop trigger if exists trg_procurement_addresses_updated_at on public.procurement_addresses;
create trigger trg_procurement_addresses_updated_at
  before update on public.procurement_addresses
  for each row execute function public.set_updated_at();

drop trigger if exists trg_purchase_orders_updated_at on public.purchase_orders;
create trigger trg_purchase_orders_updated_at
  before update on public.purchase_orders
  for each row execute function public.set_updated_at();

alter table public.procurement_addresses enable row level security;
