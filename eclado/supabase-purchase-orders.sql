create or replace function public.get_procurement_management_data()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  payload jsonb;
begin
  if not public.is_eclado_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'suppliers', coalesce((
      select jsonb_agg(to_jsonb(supplier) order by supplier.name)
      from public.suppliers supplier where supplier.active is true
    ), '[]'::jsonb),
    'supplier_items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', item.id,
        'supplier_id', item.supplier_id,
        'supplier_sku', item.supplier_sku,
        'name_en', item.name_en,
        'name_zh', item.name_zh,
        'specification', item.specification,
        'active', item.active,
        'price_id', current_price.id,
        'currency', coalesce(current_price.currency, supplier.default_currency),
        'unit_cost', current_price.unit_cost,
        'has_inventory_link', coalesce(stock.has_inventory_link, false),
        'available_stock', stock.available_stock
      ) order by item.supplier_sku)
      from public.supplier_items item
      join public.suppliers supplier on supplier.id = item.supplier_id
      left join lateral (
        select price.id, price.currency, price.unit_cost
        from public.supplier_item_prices price
        where price.supplier_item_id = item.id
          and price.effective_from <= now()
          and (price.effective_to is null or price.effective_to > now())
        order by price.effective_from desc, price.id desc
        limit 1
      ) current_price on true
      left join lateral (
        select
          count(*) > 0 as has_inventory_link,
          floor(sum(variant.stock / link.conversion_quantity))::integer as available_stock
        from public.supplier_item_variant_links link
        join public.product_variants variant on variant.id = link.product_variant_id
        where link.supplier_item_id = item.id
          and variant.active is true
      ) stock on true
      where item.active is true
    ), '[]'::jsonb),
    'addresses', coalesce((
      select jsonb_agg(to_jsonb(address) order by address.is_default desc, address.last_used_at desc nulls last, address.id desc)
      from public.procurement_addresses address where address.active is true
    ), '[]'::jsonb),
    'orders', coalesce((
      select jsonb_agg(
        to_jsonb(purchase_order) || jsonb_build_object(
          'supplier_name', supplier.name,
          'supplier_code', supplier.code,
          'items', coalesce((
            select jsonb_agg(to_jsonb(order_item) order by order_item.sort_order, order_item.id)
            from public.purchase_order_items order_item
            where order_item.purchase_order_id = purchase_order.id
          ), '[]'::jsonb)
        ) order by purchase_order.created_at desc, purchase_order.id desc
      )
      from public.purchase_orders purchase_order
      join public.suppliers supplier on supplier.id = purchase_order.supplier_id
    ), '[]'::jsonb)
  ) into payload;
  return payload;
end;
$$;

revoke all on function public.get_procurement_management_data() from public, anon;
grant execute on function public.get_procurement_management_data() to authenticated;

create or replace function public.save_procurement_address(p_address jsonb)
returns public.procurement_addresses
language plpgsql
security definer
set search_path = ''
as $$
declare
  address_id bigint := nullif(p_address ->> 'id', '')::bigint;
  saved public.procurement_addresses%rowtype;
  make_default boolean := coalesce((p_address ->> 'is_default')::boolean, false);
begin
  if not public.is_eclado_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if btrim(coalesce(p_address ->> 'address_text', '')) = '' then
    raise exception 'Shipping address is required' using errcode = '22023';
  end if;
  if make_default then
    update public.procurement_addresses set is_default = false where is_default is true;
  end if;

  if address_id is null then
    insert into public.procurement_addresses (
      address_text, is_default, active, created_by
    ) values (
      btrim(p_address ->> 'address_text'), make_default, true, auth.uid()
    ) returning * into saved;
  else
    update public.procurement_addresses set
      address_text = btrim(p_address ->> 'address_text'),
      is_default = make_default,
      active = true
    where id = address_id
    returning * into saved;
    if saved.id is null then raise exception 'Address not found' using errcode = 'P0002'; end if;
  end if;
  return saved;
end;
$$;

revoke all on function public.save_procurement_address(jsonb) from public, anon;
grant execute on function public.save_procurement_address(jsonb) to authenticated;

